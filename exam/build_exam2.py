VARIANTS = []
for v in range(5):
    r = random.Random(2000 + v)
    head = erg_pool[3 * v:3 * v + 3]
    tail = mixed_pool[12 * v:12 * v + 12]
    r.shuffle(tail)
    page = []
    for q_text, opts, correct in head + tail:
        pairs = list(enumerate(opts))
        r.shuffle(pairs)
        page.append((q_text, [o for _, o in pairs],
                     [old for old, _ in pairs].index(correct)))
    VARIANTS.append(page)

