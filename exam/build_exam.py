LETTERS = ["А", "Б", "В", "Г"]

# эргономика: первые три вопроса каждого варианта (индексы в ERG)
ERG_MATRIX = [
    [0, 1, 2],
    [3, 0, 5],
    [1, 6, 7],
    [2, 8, 9],
    [0, 10, 11],
]
USED_ERG = sorted({i for row in ERG_MATRIX for i in row})
LEFTOVER_ERG = [q for i, q in enumerate(ERG) if i not in USED_ERG]

# смешанный пул: ключевые вопросы вынесены вперёд, чтобы попасть в несколько вариантов
MIXED = ([SAN[0], SAN[1], ETAP[0], ETAP[1], ETAP[2], ETAP[3], ETAP[4], MAT[0], BIZ[0]]
         + SAN[2:] + ETAP[5:] + MAT[1:] + BIZ[1:] + LEFTOVER_ERG)

VARIANTS = []
for v in range(5):
    rnd = random.Random(1000 + v)
    head = [ERG[i] for i in ERG_MATRIX[v]]
    tail = [MIXED[(12 * v + k) % len(MIXED)] for k in range(12)]
    rnd.shuffle(tail)
    page = []
    for q_text, opts, correct in head + tail:
        pairs = list(enumerate(opts))
        rnd.shuffle(pairs)
        new_opts = [o for _, o in pairs]
        new_correct = [old for old, _ in pairs].index(correct)
        page.append((q_text, new_opts, new_correct))
    VARIANTS.append(page)

